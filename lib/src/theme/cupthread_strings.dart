  /// Resolves the appropriate strings based on the given locale.
  static CupThreadStrings fromLocale(Locale? locale) {
    if (locale == null) return en;
    switch (locale.languageCode.toLowerCase()) {
      case 'zh':
        // Traditional Chinese for Hant script or TW/HK/MO regions.
        final script = locale.scriptCode?.toLowerCase();
        final region = locale.countryCode?.toLowerCase();
        if (script == 'hant' ||
            region == 'hant' ||
            region == 'tw' ||
            region == 'hk' ||
            region == 'mo') {
          return zhHant;
        }
        return zhHans;
      case 'ja':
        return ja;
      case 'fr':
        return fr;
      case 'es':
        return es;
      case 'de':
        return de;
      case 'it':
        return it;
      case 'pt':
        return pt;
      case 'ko':
        return ko;
      case 'pl':
        return pl;
      case 'no':
      case 'nb':
      case 'nn':
        return no;
      case 'tr':
        return tr;
      case 'vi':
        return vi;
      default:
        return en;
    }
  }

